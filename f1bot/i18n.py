def t(lang: str | None, key: str, **fmt) -> str:
    """Translate ``key`` into ``lang`` (ru/uz/en) with fallback to Russian.

    Note: ``lang`` must never appear in ``fmt`` — templates use ``{lang}`` for
    the language *name*, so the positional parameter is renamed internally.
    """
    code = lang if lang in LANGS else DEFAULT_LANG
    entry = STR.get(key)
    if entry is None:
        return key
    text = entry.get(code) or entry[DEFAULT_LANG]
    return text.format(**fmt) if fmt else text


def lang_name(lang: str | None) -> str:
    return LANGS.get(lang or DEFAULT_LANG, lang or DEFAULT_LANG)
